export function inPeriod(item, period) {
  if (period === "all") return true;
  if (period === "r2") return item.round === 2;
  return item.round !== 2 && String(item.month) === period;
}

// Plan order (cluster by cluster: category, subcategories, products).
export function byPlanOrder(a, b) {
  return (a.sortOrder ?? 1e9) - (b.sortOrder ?? 1e9);
}

// Clusters in plan order, optionally limited to the items of one period.
export function deriveClusters(items) {
  return [...new Set([...items].sort(byPlanOrder).map((i) => i.cluster))].filter(Boolean);
}
